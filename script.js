const languageSelect = document.getElementById("languageSelect");

function changeLanguage(language, saveChoice = true) {
    
    const selectedTranslations = translations[language];

    document.querySelectorAll("[data-i18n]").forEach(element => {

        const translationKey = element.getAttribute("data-i18n");

        if (selectedTranslations[translationKey]) {
            element.textContent =
                selectedTranslations[translationKey];
        }

    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {

        const translationKey = element.getAttribute("data-i18n-placeholder");

        if (selectedTranslations[translationKey]) {
            element.placeholder =
                selectedTranslations[translationKey];
        }

    });

    // Change the page language
    document.documentElement.lang = language;

    // Arabic uses right-to-left layout
    if (language === "ar") {

        document.documentElement.dir = "rtl";

    } else {

        document.documentElement.dir = "ltr";

    }

    if (saveChoice) {

        localStorage.setItem(
            "selectedLanguage",
            language
        );

    }


}

languageSelect.addEventListener("change", function () {

    changeLanguage(this.value);

});

const savedLanguage = 
    localStorage.getItem("selectedLanguage")

const browserLanguage = 
    navigator.language.substring(0, 2);

const supportedLanguages =
    ["en", "es", "fr", "ar"];

let startingLanguage;

if (savedLanguage) {

    startingLanguage = savedLanguage;

} else if (supportedLanguages.includes(browserLanguage)) {

    startingLanguage = browserLanguage;

} else {

    startingLanguage = "en";

}

languageSelect.value = startingLanguage;

changeLanguage(startingLanguage, false);

